export interface TypeMatchups {
  weak4:    string[]  // 4×
  weak2:    string[]  // 2×
  resist2:  string[]  // ½×
  resist4:  string[]  // ¼×
  immune:   string[]  // 0×
}

export function computeMatchups(defenderTypes: string[]): TypeMatchups {
  const result: TypeMatchups = { weak4: [], weak2: [], resist2: [], resist4: [], immune: [] }

  for (const attacker of Object.keys(CHART)) {
    let mult = 1
    for (const defender of defenderTypes) {
      mult *= CHART[attacker]?.[defender] ?? 1
    }
    if      (mult === 4)    result.weak4.push(attacker)
    else if (mult === 2)    result.weak2.push(attacker)
    else if (mult === 0.5)  result.resist2.push(attacker)
    else if (mult === 0.25) result.resist4.push(attacker)
    else if (mult === 0)    result.immune.push(attacker)
  }

  return result
}

